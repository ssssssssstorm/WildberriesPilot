from __future__ import annotations

from marketplacepilot.models import IncomingTask, Priority, Product, Recommendation, TaskKind


class DemoDecisionEngine:
    """Прозрачная сценарная логика, имитирующая решения будущего AI-менеджера."""

    def recommend(self, incoming: IncomingTask, product: Product) -> Recommendation:
        text = f"{incoming.subject} {incoming.message}".lower()
        if incoming.kind is TaskKind.RETURN:
            return self._return_recommendation(incoming, "сроч" in text or "дефект" in text or "откле" in text)
        if incoming.kind is TaskKind.REVIEW and any(word in text for word in ("трещин", "неприят", "испорчен")):
            return Recommendation(
                "Негативный отзыв с возможным дефектом",
                Priority.HIGH,
                "Негативный отзыв о повреждении товара может повлиять на рейтинг.",
                "Здравствуйте! Нам очень жаль, что товар пришёл в таком состоянии. Передадим случай менеджеру, "
                "чтобы помочь с дальнейшим решением.",
                "Передать человеку и подготовить персональный ответ",
                ("Есть риск публичной эскалации.",),
                True,
                False,
            )
        if incoming.kind is TaskKind.REVIEW:
            return Recommendation(
                "Положительный отзыв",
                Priority.LOW,
                "Положительный отзыв не требует срочного ответа.",
                f"Спасибо за отзыв о товаре «{product.name}»! Очень рады, что покупка вам понравилась.",
                "Подтвердить публикацию ответа в симуляции",
                (),
                False,
                False,
            )
        if "совместим" in text or "lenovo" in text:
            return Recommendation(
                "Проверка совместимости",
                Priority.HIGH,
                "Точная совместимость зависит от характеристик конкретной модели устройства.",
                "Здравствуйте! Для точного ответа по совместимости передадим запрос менеджеру: он сверит "
                "характеристики вашей модели с параметрами зарядного устройства.",
                "Передать человеку для проверки спецификации",
                ("Нельзя обещать совместимость без сверки параметров.",),
                True,
                False,
            )
        if "размер" in text or "рост" in text:
            return Recommendation(
                "Вопрос о размере",
                Priority.NORMAL,
                "Типовой вопрос до покупки.",
                "Здравствуйте! При росте 172 см обычно ориентируются на размер M. Если планируете носить "
                "ветровку поверх плотного слоя, можно рассмотреть L. Рекомендуем свериться с таблицей замеров.",
                "Подтвердить ответ в симуляции",
                (),
                False,
                False,
            )
        if "комплект" in text or "крышк" in text:
            return Recommendation(
                "Вопрос о комплектации",
                Priority.NORMAL,
                "Типовой вопрос о составе набора.",
                "Здравствуйте! В наборе пять контейнеров и пять соответствующих крышек — крышки не считаются "
                "как отдельные позиции.",
                "Подтвердить ответ в симуляции",
                (),
                False,
                False,
            )
        if "батаре" in text:
            return Recommendation(
                "Вопрос о первом запуске",
                Priority.NORMAL,
                "Комплектация товара известна и не требует проверки.",
                "Здравствуйте! Для кухонных весов нужны две батарейки AAA — они не входят в комплект. После установки "
                "батареек весы должны включиться. Если проблема сохранится, пожалуйста, напишите нам.",
                "Подтвердить ответ в симуляции",
                (),
                False,
                False,
            )
        if "достав" in text or "сборк" in text:
            return Recommendation(
                "Статус доставки",
                Priority.NORMAL,
                "Вопрос относится к логистике Wildberries и не содержит признаков риска.",
                "Здравствуйте! Статус доставки обновляет Wildberries после передачи заказа в логистику. Рекомендуем "
                "проверить карточку заказа чуть позже — мы со своей стороны передадим информацию в магазин.",
                "Подтвердить ответ в симуляции",
                ("Точный срок доставки зависит от Wildberries."),
                False,
                False,
            )
        return Recommendation(
            "Общее обращение",
            Priority.NORMAL,
            "Обращение ожидает стандартной обработки.",
            "Здравствуйте! Спасибо за обращение. Мы уточним детали и вернёмся с ответом.",
            "Передать человеку для уточнения",
            ("Не удалось отнести обращение к безопасному сценарию."),
            True,
            False,
        )

    @staticmethod
    def _return_recommendation(incoming: IncomingTask, urgent: bool) -> Recommendation:
        priority = Priority.URGENT if urgent else Priority.HIGH
        reason = "Срок ответа сегодня; заявлен дефект товара."
        if not urgent:
            reason = "Возврат требует проверки и решения человека."
        return Recommendation(
            "Заявка на возврат",
            priority,
            reason,
            "Здравствуйте! Заявку на возврат передали менеджеру для проверки. Решение будет принято после "
            "подтверждения ответственным сотрудником.",
            "Запросить подтверждение человека по возврату",
            ("Возврат нельзя автоматически одобрять или отклонять."),
            True,
            True,
        )
